# tools/format_email.py
# Formats research JSON into clean morning email body

import json
from datetime import datetime


def format_email_report(research_data: str) -> str:
    """
    Formats raw research JSON from Research Agent
    into a clean structured morning email body.

    Args:
        research_data: JSON string from Research Agent
    Returns:
        Formatted email body string
    """
    try:
        data = json.loads(research_data)
    except Exception:
        return f"Unable to parse research data.\n{research_data[:200]}"

    date     = datetime.now().strftime("%d %B %Y")
    day      = datetime.now().strftime("%A")
    indices  = data.get("market_indices", {})
    gainers  = data.get("top_gainers_formatted", "")
    losers   = data.get("top_losers_formatted", "")
    news     = data.get("top_news", [])
    summary  = data.get("news_summary", "")
    papers   = data.get("research_papers", [])
    company  = data.get("company_background", {})
    fetched  = data.get("fetched_at", "")

    # Market indices section
    index_lines = []
    for name, vals in indices.items():
        if not isinstance(vals, dict):
            continue
        direction = str(vals.get("direction", "")).upper()
        arrow     = "UP  ▲" if "UP" in direction else "DOWN ▼"
        pct       = vals.get("change_percent", 0)
        val       = vals.get("value", 0)
        index_lines.append(
            f"  {name.replace('_', ' ').upper():<15}"
            f"  {val:>10,.2f}"
            f"  {arrow}  {pct:>+.2f}%"
        )
    market_section = (
        "\n".join(index_lines)
        if index_lines
        else "  Data not available"
    )

    # News section
    news_lines = []
    for i, item in enumerate(news[:5], 1):
        if not isinstance(item, dict):
            continue
        title = item.get("title", "")[:90]
        url   = item.get("url", "")
        if title:
            news_lines.append(f"  {i}. {title}")
            if url:
                news_lines.append(f"     {url}")
    news_section = (
        "\n".join(news_lines)
        if news_lines
        else "  No news available"
    )

    # Research papers section
    paper_lines = []
    for i, p in enumerate(papers[:2], 1):
        if not isinstance(p, dict):
            continue
        title = p.get("title", "")[:80]
        paper_lines.append(f"  {i}. {title}")
    papers_section = (
        "\n".join(paper_lines)
        if paper_lines
        else "  No papers available"
    )

    # Company background
    company_section = ""
    if company.get("found"):
        company_section = (
            f"\n\n  {company.get('title', '')}: "
            f"{company.get('summary', '')[:150]}"
        )

    # Build full email
    email = f"""
==================================================
  FINBRIEF AI — MORNING MARKET BRIEFING
  {day}, {date}
==================================================

MARKET INDICES
--------------------------------------------------
{market_section}

TOP GAINERS
--------------------------------------------------
{gainers if gainers else "  Data not available"}

TOP LOSERS
--------------------------------------------------
{losers if losers else "  Data not available"}

TOP FINANCIAL NEWS
--------------------------------------------------
{news_section}

MARKET SUMMARY
--------------------------------------------------
  {summary}

RESEARCH HIGHLIGHT
--------------------------------------------------
{papers_section}
{company_section}

==================================================
  Generated by FinBrief AI  |  Data at: {fetched}
  Full data available in attached Excel report
==================================================
""".strip()

    return email
